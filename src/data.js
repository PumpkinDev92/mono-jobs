function rng(seed) {
  let s = seed;
  return () => ((s = (s * 1664525 + 1013904223) % 4294967296) / 4294967296);
}

export function buildJobs() {
  const rand = rng(42);
  const pick = (arr) => arr[Math.floor(rand() * arr.length)];
  const jobs = [];
  let id = 1;
  for (let round = 0; round < 3; round++) {
    for (const [title, category, company, min, max] of TEMPLATES) {
      const shift = 1 + (rand() - 0.5) * 0.2;
      const salary = Math.round((min + rand() * (max - min)) * shift / 500) * 500;
      jobs.push({
        id: id++,
        title,
        category,
        company,
        city: pick(CITIES),
        type: pick(TYPES),
        experience: category === 'IT та розробка' ? pick(EXPERIENCE.slice(1)) : pick(EXPERIENCE),
        salary,
        daysAgo: Math.floor(rand() * 20),
        description: pick(DESCRIPTIONS),
        duties: [...DUTIES].sort(() => rand() - 0.5).slice(0, 3),
        perks: [...PERKS].sort(() => rand() - 0.5).slice(0, 3),
        requirements: [...REQS].sort(() => rand() - 0.5).slice(0, 3),
        schedule: pick(SCHEDULES),
        addresses: [pick(STREETS) + ' ' + (1 + Math.floor(rand() * 90)), pick(STREETS) + ' ' + (1 + Math.floor(rand() * 90))],
        viewers: 3 + Math.floor(rand() * 40),
        hot: rand() > 0.7,
      });
    }
  }
  return jobs;
}
